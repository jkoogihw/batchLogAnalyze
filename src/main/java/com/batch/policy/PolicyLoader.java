package com.batch.policy;

/**
 * =====================================================================================
 * [의존 역전 원칙 (DIP) 인터페이스: 정책 로더]
 * -------------------------------------------------------------------------------------
 * 💡 OOP 설계 원칙:
 * 1. DIP (Dependency Inversion Principle: 의존 역전 원칙):
 *    - PolicyManager가 구체적인 파일 I/O나 클래스패스 로딩 기술에 직접 의존하지 않고,
 *      PolicyLoader 추상화에 의존하도록 설계합니다.
 * 2. 테스트 용이성 (Testability):
 *    - 테스트 시 인메모리 MockPolicyLoader로 쉽게 교체하여 테스트할 수 있습니다.
 * =====================================================================================
 */
public interface PolicyLoader {

    /**
     * 정책 데이터 로드
     *
     * @param location 파일 경로 또는 리소스 이름
     * @return 로드된 JSON 원본 문자열 (실패 또는 미발견 시 null)
     */
    String load(String location);
}
